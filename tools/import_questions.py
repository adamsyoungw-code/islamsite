def main():
    data = json.loads(DATA_PATH.read_text(encoding="utf-8"))
    n_q = n_f = n_t = 0
    for sec in data["sections"]:
        for cyc in sec["cycles"]:
            if cyc["id"] in CYCLE_FINAL:
                cyc["finalTestUrl"] = CYCLE_FINAL[cyc["id"]]
            for les in cyc["lessons"]:
                if les["id"] in QUESTIONS:
                    les["questions"] = QUESTIONS[les["id"]]
                    n_q += 1
                if les["id"] in QUIZZES:
                    # встроенный тест на сайте заменяет гугл-форму
                    les["tests"] = QUIZZES[les["id"]]
                    les.pop("testUrl", None)
                    n_t += 1
                elif les["id"] in FORMS:
                    les["testUrl"] = FORMS[les["id"]]
                    les.pop("tests", None)
                    n_f += 1
    DATA_PATH.write_text(
        json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    print(f"Вопросы: {n_q} уроков; встроенные тесты: {n_t}; ссылки на формы: {n_f}.")


if __name__ == "__main__":
    main()
